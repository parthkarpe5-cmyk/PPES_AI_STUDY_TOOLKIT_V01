import { NextRequest, NextResponse } from 'next/server';
import {
  FeedbackExperience,
  FeedbackCategory,
  FeedbackClass,
  FEEDBACK_CATEGORIES,
  FEEDBACK_EXPERIENCES,
  FEEDBACK_CLASSES,
} from '@/data/feedback';

// ---------------------------------------------------------------------------
// Rate limiter: max 5 submissions per IP per 10 minutes (in-memory, per instance)
// ---------------------------------------------------------------------------
const ipSubmissionTimestamps = new Map<string, number[]>();
const RATE_LIMIT_WINDOW_MS = 10 * 60 * 1000;
const MAX_SUBMISSIONS_PER_WINDOW = 5;

function isRateLimited(ip: string): boolean {
  const now = Date.now();
  const timestamps = ipSubmissionTimestamps.get(ip) || [];
  const recent = timestamps.filter((t) => now - t < RATE_LIMIT_WINDOW_MS);

  if (recent.length >= MAX_SUBMISSIONS_PER_WINDOW) return true;

  recent.push(now);
  ipSubmissionTimestamps.set(ip, recent);

  // Periodic cleanup to prevent unbounded memory growth
  if (ipSubmissionTimestamps.size > 1000) {
    for (const [key, times] of ipSubmissionTimestamps.entries()) {
      const valid = times.filter((t) => now - t < RATE_LIMIT_WINDOW_MS);
      if (valid.length === 0) ipSubmissionTimestamps.delete(key);
      else ipSubmissionTimestamps.set(key, valid);
    }
  }
  return false;
}

// ---------------------------------------------------------------------------
// Validated allowed value sets
// ---------------------------------------------------------------------------
const VALID_EXPERIENCES = new Set<string>(FEEDBACK_EXPERIENCES.map((e) => e.value));
const VALID_CATEGORIES = new Set<string>(FEEDBACK_CATEGORIES);
const VALID_CLASSES = new Set<string>(['', ...FEEDBACK_CLASSES.map((c) => c.value)]);

export async function POST(request: NextRequest) {
  try {
    // 1. IP rate limiting
    const ip =
      request.headers.get('x-forwarded-for')?.split(',')[0]?.trim() ||
      request.headers.get('x-real-ip') ||
      'anonymous';

    if (isRateLimited(ip)) {
      return NextResponse.json(
        { success: false, error: 'Too many submissions. Please wait a few minutes and try again.' },
        { status: 429 }
      );
    }

    // 2. Parse body
    let body: Record<string, unknown>;
    try {
      body = await request.json();
    } catch {
      return NextResponse.json(
        { success: false, error: 'Invalid request format.' },
        { status: 400 }
      );
    }

    // 3. Honeypot anti-spam check (invisible to humans, bots fill it)
    if (typeof body.websiteUrl === 'string' && body.websiteUrl.trim().length > 0) {
      // Silently discard — do not reveal why to the bot
      return NextResponse.json({ success: true, message: 'Received' });
    }

    // 4. Extract and coerce fields (matching exact Apps Script field names)
    const experience = (typeof body.experience === 'string' ? body.experience : '').trim() as FeedbackExperience;
    const category   = (typeof body.category   === 'string' ? body.category   : '').trim() as FeedbackCategory;
    const feedback   = (typeof body.feedback   === 'string' ? body.feedback   : '').trim();
    const studentClass = (typeof body.studentClass === 'string' ? body.studentClass : '').trim() as FeedbackClass;
    // requestId is generated by the browser and forwarded for dedup
    const requestId = typeof body.requestId === 'string' && /^[a-zA-Z0-9_-]{8,64}$/.test(body.requestId)
      ? body.requestId
      : null;

    // 5. Server-side validation
    if (!VALID_EXPERIENCES.has(experience)) {
      return NextResponse.json(
        { success: false, error: 'Please choose an experience rating (Good, Okay, or Difficult).' },
        { status: 400 }
      );
    }

    if (!VALID_CATEGORIES.has(category)) {
      return NextResponse.json(
        { success: false, error: 'Please select a valid feedback category.' },
        { status: 400 }
      );
    }

    if (feedback.length < 5) {
      return NextResponse.json(
        { success: false, error: 'Please write at least a few words describing your feedback.' },
        { status: 400 }
      );
    }

    if (feedback.length > 2000) {
      return NextResponse.json(
        { success: false, error: 'Feedback is too long (maximum 2,000 characters).' },
        { status: 400 }
      );
    }

    if (studentClass && !VALID_CLASSES.has(studentClass)) {
      return NextResponse.json(
        { success: false, error: 'Invalid class selection.' },
        { status: 400 }
      );
    }

    // 6. Build payload exactly matching the Apps Script receiver's expected field names
    const receiverPayload = {
      experience,
      category,
      feedback,
      studentClass: studentClass || 'Not specified',
      // Server-only credential — never sent to browser
      secretToken: process.env.FEEDBACK_SHARED_SECRET ?? '',
      // Forwarded request ID for Apps Script CacheService deduplication
      ...(requestId ? { requestId } : {}),
    };

    // 7. Forward to Apps Script Web App (server-to-server only)
    const appsScriptUrl = process.env.FEEDBACK_SCRIPT_URL;

    if (!appsScriptUrl) {
      // Development fallback: log payload, simulate success
      console.warn('[feedback] FEEDBACK_SCRIPT_URL is not set — simulating success locally.');
      console.log('[feedback] Payload that would be sent:', {
        ...receiverPayload,
        secretToken: '[REDACTED]',
      });
      return NextResponse.json({
        success: true,
        saved: true,
        message: 'Thank you! Your feedback helps PPES improve the toolkit.',
      });
    }

    let upstreamRes: Response;
    try {
      upstreamRes = await fetch(appsScriptUrl, {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify(receiverPayload),
        // Apps Script Web Apps redirect via 302 — must follow
        redirect: 'follow',
        signal: AbortSignal.timeout(20_000),
      });
    } catch (networkError: unknown) {
      const msg = networkError instanceof Error ? networkError.message : String(networkError);
      console.error('[feedback] Network error reaching Apps Script:', msg);
      return NextResponse.json(
        { success: false, error: 'Feedback server is unreachable. Please try again later.' },
        { status: 504 }
      );
    }

    // 8. Parse and validate the upstream response
    let upstreamData: Record<string, unknown>;
    try {
      const rawText = await upstreamRes.text();
      console.log('[feedback] Apps Script raw response (status', upstreamRes.status, '):', rawText);
      upstreamData = JSON.parse(rawText) as Record<string, unknown>;
    } catch {
      console.error('[feedback] Apps Script returned non-JSON, status:', upstreamRes.status);
      return NextResponse.json(
        { success: false, error: 'Unexpected response from feedback server.' },
        { status: 502 }
      );
    }

    // Accept status:"success" AND saved:true (set by the updated Apps Script).
    // The saved:true field was added in the receiver update — redeploy Apps Script if missing.
    if (upstreamData.status === 'success' && upstreamData.saved === true) {
      return NextResponse.json({
        success: true,
        saved: true,
        duplicate: upstreamData.duplicate === true,
        message: 'Thank you! Your feedback helps PPES improve the toolkit.',
      });
    }

    // Upstream returned an error or unexpected response
    console.error('[feedback] Apps Script rejected submission:', upstreamData);
    return NextResponse.json(
      {
        success: false,
        error:
          typeof upstreamData.message === 'string'
            ? upstreamData.message
            : 'Feedback could not be recorded. Please try again.',
      },
      { status: 502 }
    );
  } catch (error: unknown) {
    const msg = error instanceof Error ? error.message : String(error);
    console.error('[feedback] Unhandled exception:', msg);
    return NextResponse.json(
      { success: false, error: 'An unexpected error occurred. Please try again.' },
      { status: 500 }
    );
  }
}
